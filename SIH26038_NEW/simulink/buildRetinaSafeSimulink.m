%% RetinaSafe Telemedicine Simulation
% Complete rebuild of the prototype Simulink workflow

scriptRoot = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptRoot);
model = 'S11_telemedicine_simulation';
modelFile = fullfile(scriptRoot, [model '.slx']);
backupFile = fullfile(scriptRoot, [model '.prebuild.bak.slx']);

if ~isfile(modelFile)
    error('Simulink model not found: %s', modelFile);
end

% Preserve the checked-in model before any destructive rebuild operation.
if ~isfile(backupFile)
    copyfile(modelFile, backupFile);
end

%% Load model
if bdIsLoaded(model)
    close_system(model, 0);
end
load_system(modelFile);

%% Remove all existing blocks and lines
% Start from a completely clean canvas.
delete_line(find_system(model, ...
    'FindAll', 'on', ...
    'Type', 'Line'));

blocks = find_system(model, ...
    'SearchDepth', 1, ...
    'Type', 'Block');

for k = 1:numel(blocks)
    if ~strcmp(blocks{k}, model)
        delete_block(blocks{k});
    end
end

%% Simulation settings
set_param(model, 'StopTime', '600');

%% Main workflow positions

y = 160;

x1 = 40;
x2 = 180;
x3 = 330;
x4 = 480;
x5 = 630;
x6 = 780;
x7 = 940;

%% 1. PATIENT ARRIVALS

add_block( ...
    'simulink/Sources/Pulse Generator', ...
    [model '/Patient Arrivals'], ...
    'Position', [x1 y x1+100 y+50]);

set_param( ...
    [model '/Patient Arrivals'], ...
    'Amplitude', '1', ...
    'Period', '60', ...
    'PulseWidth', '10', ...
    'PhaseDelay', '0');

%% 2. FUNDUS IMAGE CAPTURE

add_block( ...
    'simulink/Continuous/Transport Delay', ...
    [model '/Fundus Image Capture'], ...
    'Position', [x2 y x2+110 y+50]);

set_param( ...
    [model '/Fundus Image Capture'], ...
    'DelayTime', '30');

%% 3. IMAGE QUALITY CHECK

add_block( ...
    'simulink/Continuous/Transport Delay', ...
    [model '/Image Quality Check'], ...
    'Position', [x3 y x3+110 y+50]);

set_param( ...
    [model '/Image Quality Check'], ...
    'DelayTime', '5');

%% 4. TELEMEDICINE NETWORK

add_block( ...
    'simulink/Continuous/Transport Delay', ...
    [model '/Telemedicine Network'], ...
    'Position', [x4 y x4+110 y+50]);

set_param( ...
    [model '/Telemedicine Network'], ...
    'DelayTime', '10');

%% 5. AI SCREENING

add_block( ...
    'simulink/Continuous/Transport Delay', ...
    [model '/AI Screening'], ...
    'Position', [x5 y x5+100 y+50]);

set_param( ...
    [model '/AI Screening'], ...
    'DelayTime', '20');

%% 6. OPHTHALMOLOGIST REVIEW

add_block( ...
    'simulink/Continuous/Transport Delay', ...
    [model '/Ophthalmologist Review'], ...
    'Position', [x6 y x6+120 y+50]);

set_param( ...
    [model '/Ophthalmologist Review'], ...
    'DelayTime', '60');

%% 7. FINAL DECISION

add_block( ...
    'simulink/Sinks/Display', ...
    [model '/Final Decision'], ...
    'Position', [x7 y x7+100 y+50]);

%% Connect main workflow

add_line(model, ...
    'Patient Arrivals/1', ...
    'Fundus Image Capture/1');

add_line(model, ...
    'Fundus Image Capture/1', ...
    'Image Quality Check/1');

add_line(model, ...
    'Image Quality Check/1', ...
    'Telemedicine Network/1');

add_line(model, ...
    'Telemedicine Network/1', ...
    'AI Screening/1');

add_line(model, ...
    'AI Screening/1', ...
    'Ophthalmologist Review/1');

add_line(model, ...
    'Ophthalmologist Review/1', ...
    'Final Decision/1');

%% Workflow scope

add_block( ...
    'simulink/Sinks/Scope', ...
    [model '/Workflow Output'], ...
    'Position', [940 260 1040 310]);

add_line(model, ...
    'Ophthalmologist Review/1', ...
    'Workflow Output/1');

%% ============================================================
%  LATENCY CALCULATION
% =============================================================

baseY = 400;

%% Capture time

add_block( ...
    'simulink/Sources/Constant', ...
    [model '/Capture Time'], ...
    'Value', '30', ...
    'Position', [50 baseY 110 baseY+30]);

%% Quality time

add_block( ...
    'simulink/Sources/Constant', ...
    [model '/Quality Time'], ...
    'Value', '5', ...
    'Position', [180 baseY 240 baseY+30]);

%% Network time

add_block( ...
    'simulink/Sources/Constant', ...
    [model '/Network Time'], ...
    'Value', '10', ...
    'Position', [310 baseY 370 baseY+30]);

%% AI time

add_block( ...
    'simulink/Sources/Constant', ...
    [model '/AI Time'], ...
    'Value', '20', ...
    'Position', [440 baseY 500 baseY+30]);

%% Doctor time

add_block( ...
    'simulink/Sources/Constant', ...
    [model '/Doctor Time'], ...
    'Value', '60', ...
    'Position', [570 baseY 630 baseY+30]);

%% Add block

add_block( ...
    'simulink/Math Operations/Add', ...
    [model '/Total Latency'], ...
    'Inputs', '+++++', ...
    'Position', [700 baseY-5 740 baseY+35]);

%% Display total

add_block( ...
    'simulink/Sinks/Display', ...
    [model '/Total Processing Time'], ...
    'Position', [800 baseY-5 930 baseY+35]);

%% Connect latency inputs

add_line(model, ...
    'Capture Time/1', ...
    'Total Latency/1');

add_line(model, ...
    'Quality Time/1', ...
    'Total Latency/2');

add_line(model, ...
    'Network Time/1', ...
    'Total Latency/3');

add_line(model, ...
    'AI Time/1', ...
    'Total Latency/4');

add_line(model, ...
    'Doctor Time/1', ...
    'Total Latency/5');

%% Connect total latency display

add_line(model, ...
    'Total Latency/1', ...
    'Total Processing Time/1');

%% ============================================================
%  LABELS / ANNOTATIONS
% =============================================================

Simulink.Annotation( ...
    model, ...
    'RURAL PHC  ->  TELEMEDICINE NETWORK  ->  AI  ->  OPHTHALMOLOGIST');

Simulink.Annotation( ...
    model, ...
    'Total sequential processing time = 125 seconds');

%% Save

save_system(model, modelFile);

%% Fit model to screen

set_param(model, 'ZoomFactor', 'FitSystem');

%% Finish

disp(' ');
disp('==============================================');
disp(' RetinaSafe Telemedicine Simulation READY');
disp('==============================================');
disp(' Patient arrival interval     = 60 seconds');
disp(' Fundus capture               = 30 seconds');
disp(' Image quality check          = 5 seconds');
disp(' Network transmission         = 10 seconds');
disp(' AI processing                = 20 seconds');
disp(' Ophthalmologist review       = 60 seconds');
disp(' --------------------------------------------');
disp(' Total sequential latency     = 125 seconds');
disp(' Simulation duration          = 600 seconds');
disp('==============================================');